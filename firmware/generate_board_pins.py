"""Generate the experimental firmware pin map from its carrier PCB config."""
import argparse
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
CONFIG = HERE.parent / "pcb" / "carrier-config.json"
TARGET = HERE / "gun_mouse_supermini" / "board_pins.h"
REQUIRED = {"JOY_X", "JOY_Y", "JOY_SW", "BTN_R", "TRIG", "SDA", "SCL", "TOUCH", "VBAT_ADC", "VBUS_DET"}


def render(config_path=CONFIG):
    config_path = Path(config_path)
    config = json.loads(config_path.read_text(encoding="utf-8"))
    pins = config["firmware_pins"]
    if set(pins) != REQUIRED or any(type(gpio) is not int for gpio in pins.values()):
        raise ValueError("carrier-config firmware_pins must contain the ten named GPIO integer mappings")
    if len(set(pins.values())) != len(pins):
        raise ValueError("carrier-config assigns multiple signals to one GPIO")
    if set(pins.values()) & {3, 19, 20, 45, 46}:
        raise ValueError("strap/native USB GPIOs must not be assigned to the carrier")
    if not set(pins.values()) <= set(range(1, 14)) | {43, 44}:
        raise ValueError("GPIO is not on this SuperMini's two 9-pin rows")
    for signal in ("JOY_X", "JOY_Y", "VBAT_ADC", "VBUS_DET"):
        if not 1 <= pins[signal] <= 10:
            raise ValueError(f"{signal} must use ADC1 GPIO1..10")
    if not 1 <= pins["TOUCH"] <= 14 or not 0 <= pins["TRIG"] <= 21:
        raise ValueError("touch/RTC wake pin is invalid for ESP32-S3")
    digest = hashlib.sha256(config_path.read_bytes()).hexdigest()
    lines = ["#pragma once", "", "// Generated by firmware/generate_board_pins.py; do not edit GPIOs by hand.",
             "// Source: experiments/30g-onepiece-test-shell/carrier-config.json", "// Carrier config SHA256: " + digest,
             "// TENSTAR ESP32-S3FH4R2 SuperMini: 4MB flash / 2MB QSPI PSRAM, two 9-pin rows.",
             "namespace GunMouse {", "namespace Pins {"]
    lines += [f"constexpr int {signal} = {pins[signal]};" for signal in sorted(pins)]
    lines += ["// GPIO19/20 are native USB inside the module; no carrier connection.",
              "// IMU interrupts are not connected; the sensor is polled over I2C.",
              "// VBUS_DET is ADC1: 100k/100k divider on the shared 5V/VBUS rail.",
              "}  // namespace Pins", "}  // namespace GunMouse", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=CONFIG)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render(args.config)
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
            raise SystemExit("board_pins.h is stale; run generate_board_pins.py")
    else:
        TARGET.write_text(content, encoding="utf-8")
    print(f"Pin map {'verified' if args.check else 'generated'}: {TARGET}")


if __name__ == "__main__":
    main()
