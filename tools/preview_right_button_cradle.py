"""快速装配预览用右键侧按 U 托；只返回实体，不写出文件。"""


def move_right_button_cradle(m, base):
    """为中心 (-19.15, -10.8, -31) 的侧按右键让位并接入原 H4。"""
    # 按钮朝 +X；背后的低挡边承受按压力，三根脚从其上方引出。
    additions = [
        m.box(-24.2, -15.7, -18.7, -3.5, -35.6, -34.1),
        m.box(-24.2, -15.7, -18.7, -17.4, -34.2, -27.8),
        m.box(-24.2, -15.7, -4.2, -3.5, -34.2, -27.8),
        m.box(-24.2, -22.6, -18.7, -3.5, -34.2, -32.4),
        m.beam((-27, -27), (-22.9, -34.7), 3.6),
    ]
    result = m.fuse([base, *additions])
    # 只切开挤入外壳、焊脚及手指进出通道的旧斜筋，保留外侧 U 托。
    cuts = [
        m.box(-22.55, -15.75, -17.35, -4.25, -34.05, -27.95),
        m.box(-25.0, -22.25, -16.75, -4.85, -31.85, -30.15),
        m.cx(-8.85, -31, 5, -14.95, 5),
        m.cy(-27, -27, 1.2, -21, m.BACK + .2),
    ]
    for cut in cuts:
        result = result.cut(cut)
    return result.clean()
